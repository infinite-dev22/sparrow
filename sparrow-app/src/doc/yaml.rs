//! SDK-independent YAML syntax validation for config files, including pubspec.lock.
use lsp_types::{Diagnostic, DiagnosticSeverity, Position, Range};
use serde::Deserialize;

pub(super) const SOURCE: &str = "Sparrow YAML";

pub(super) fn is_builtin(diagnostic: &Diagnostic) -> bool {
    diagnostic.source.as_deref() == Some(SOURCE)
}

pub(super) fn diagnostics(text: &str) -> Vec<Diagnostic> {
    // A YAML stream may legally contain several documents. Deserializing Values
    // also catches duplicate mapping keys, unresolved aliases and invalid tags.
    for document in serde_yaml::Deserializer::from_str(text) {
        if let Err(error) = serde_yaml::Value::deserialize(document) {
            let location = error.location();
            let start = position(
                text,
                location.as_ref().map(|p| p.line()).unwrap_or(1),
                location.as_ref().map(|p| p.column()).unwrap_or(1),
            );
            let line = text.lines().nth(start.line as usize).unwrap_or("");
            let next = line
                .chars()
                .scan(0u32, |column, c| {
                    let begin = *column;
                    *column += c.len_utf16() as u32;
                    Some((begin, *column))
                })
                .find(|(begin, _)| *begin >= start.character)
                .map(|(_, end)| end)
                .unwrap_or(start.character);
            return vec![Diagnostic {
                range: Range::new(start, Position::new(start.line, next)),
                severity: Some(DiagnosticSeverity::ERROR),
                source: Some(SOURCE.into()),
                message: error.to_string(),
                ..Default::default()
            }];
        }
    }
    vec![]
}
fn position(text: &str, line: usize, column: usize) -> Position {
    let lines = text.split('\n').collect::<Vec<_>>();
    let line = line.saturating_sub(1).min(lines.len().saturating_sub(1));
    // libyaml columns count characters; the editor protocol counts UTF-16 units.
    let character = lines[line]
        .trim_end_matches('\r')
        .chars()
        .take(column.saturating_sub(1))
        .map(|c| c.len_utf16() as u32)
        .sum();
    Position::new(line as u32, character)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn accepts_lockfiles_and_yaml_streams_and_reports_real_errors() {
        for text in [
            "",
            "# Generated by pub\npackages:\n  async:\n    dependency: transitive\n    version: '2.13.0'\nsdks:\n  dart: '>=3.4.0 <4.0.0'\n",
            "a: &value 1\nb: *value\n---\nnext: true\n",
        ] {
            assert!(diagnostics(text).is_empty(), "{text}");
        }
        for text in [
            "packages: [",
            "packages:\n  async: 1\n  async: 2\n",
            "a: *missing\n",
            "key:\n\tvalue: 1\n",
        ] {
            let result = diagnostics(text);
            assert_eq!(result.len(), 1, "{text}");
            assert!(is_builtin(&result[0]));
            assert_eq!(result[0].severity, Some(DiagnosticSeverity::ERROR));
        }
        assert!(diagnostics("packages: {}\n").is_empty());
    }
    #[test]
    fn locations_use_utf16_and_handle_crlf_and_eof() {
        let result = diagnostics("é🙂: @bad\r\n");
        assert_eq!(result[0].range.start, Position::new(0, 5));
        assert_eq!(result[0].range.end, Position::new(0, 6));
        let result = diagnostics("packages: [\n");
        assert!(result[0].range.start.line <= 1);
        assert_eq!(position("é🙂: x\r\n", 1, 3), Position::new(0, 3));
    }
    #[test]
    fn repairs_and_server_updates_preserve_the_other_diagnostic_source() {
        use crate::doc::DiagnosticData;
        use floem::reactive::{Scope, SignalGet};
        use lapce_xi_rope::spans::SpansBuilder;
        let scope = Scope::new();
        let data = DiagnosticData {
            expanded: scope.create_rw_signal(true),
            diagnostics: scope.create_rw_signal(im::Vector::new()),
            diagnostics_span: scope.create_rw_signal(SpansBuilder::new(0).build()),
        };
        data.set_yaml(diagnostics("packages: ["));
        let external =
            Diagnostic::new_simple(Range::default(), "Schema error".into());
        data.set_external([external.clone()]);
        assert_eq!(data.diagnostics.get_untracked().len(), 2);
        data.set_yaml(diagnostics("packages: {}"));
        assert_eq!(data.diagnostics.get_untracked(), im::vector![external]);
        data.set_yaml(diagnostics("packages: ["));
        data.set_external([]);
        assert_eq!(data.diagnostics.get_untracked().len(), 1);
        assert!(is_builtin(&data.diagnostics.get_untracked()[0]));
        data.set_yaml(vec![]);
        assert!(data.diagnostics.get_untracked().is_empty());
        scope.dispose();
    }
}
